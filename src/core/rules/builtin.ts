const SOFTENER_PATTERNS = [
	String.raw`(?<=\b(?:I|you|we|they|he|she|it|it's|that's|is|was|are|were|am|be|been|feels|felt|seems|looks|sounds|just|really)\s+)(?:kind|sort) of\b`,
	String.raw`\bin a way(?=\s*[,.;:!?)]|\s*$)`,
];

const AI_PATTERNS = [
	String.raw`\bnot (?:just|merely|simply) (?:about )?[^.!?;:]{1,60}?(?:,|;|—|--)?\s*\b(?:but|it's|it is|they're|they are|we're|we are|this is)\b`,
	String.raw`\b(?:it|this|that)(?:'s not| is not| isn't) (?:about )?[^.!?;,—]{1,50}(?:,|;|—|--)\s*(?:it|this|that)(?:'s| is)\b`,
	String.raw`(?<=,\s*)(?:highlighting|emphasi[sz]ing|symboli[sz]ing|cementing|solidifying|cultivating|encompassing|reinforcing|signall?ing)\s+(?:the|a|an|its|their|his|her|our|how|that|this)\b`,
	String.raw`\b(?:serves|served|stands|stood) as an? (?:reminder|symbol|cornerstone|catalyst)\b`,
];

const LINKEDIN_CLOSER_PATTERNS = [
	String.raw`^\W*(?:agree|disagree|thoughts|am I wrong|who's with me|who else|sound familiar|thoughts below|what do you think|what would you add|what's your take|what are your thoughts|anyone else|can you relate|still with me)\?\W*$`,
	String.raw`^\W*the (?:lesson|result|truth|secret|kicker|best part|catch|twist|answer|reason|takeaway|problem|outcome)\?\W*$`,
];

const EMOJI_BULLET_PATTERN = String.raw`(?:^|\n)[ \t]*(?:(?![©®™])\p{Extended_Pictographic}|\d\uFE0F?\u20E3|[→►➜➤✓])`;

const DOUBLED_WORD_PATTERN = String.raw`\b(?!(?:that|had|is|do|so|no|very|bye|ha|now|well|really|many|far|more|again|blah|knock|chop|round|over|bit|by)\b)(\p{L}+)\s+\1\b`;

const PASSIVE_PATTERN = [
	String.raw`\b(?:am|is|are|was|were|be|been|being)\s+`,
	String.raw`(?:(?:not|never|also|often|always|already|just|then|still|now|soon|\p{L}+ly)\s+){0,2}`,
	String.raw`(?!(?:used|supposed)\s+to\b)`,
	String.raw`(?!(?:${ADJECTIVE_PARTICIPLES.join("|")})\b)`,
	String.raw`(?:\p{L}{2,}ed|${IRREGULAR_PARTICIPLES.join("|")})\b`,
	String.raw`\s+by\b(?!\s+(?:default|hand|far|now|then|accident|chance|design|mistake|itself|themselves|the end|the time|\d))`,
].join("");

